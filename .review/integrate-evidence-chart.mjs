import { readFile, writeFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const path = 'src/pages/CategoryDetail.tsx';
let source = await readFile(path, 'utf8');
assert.ok(!source.includes('@/components/category/EvidenceComparisonPanel'), 'Already integrated; refuse duplicate rewrite');
const marker = source.indexOf('S1.5 全類別視覺化保障限額圖表');
let component;
if (marker >= 0) component = source.slice(marker).match(/<([A-Z][A-Za-z0-9_]*)\b/)?.[1];
const imports = [...source.matchAll(/import\s+([A-Za-z0-9_]+)\s+from\s+(["'])([^"']+)\2\s*;/g)];
if (!component) {
  const candidates = imports.filter(match => /Coverage.*(?:Chart|Visual)|(?:Chart|Visual).*Coverage/.test(match[1]));
  assert.equal(candidates.length, 1, 'Cannot safely identify the coverage visual; inspect the source rather than broad-replacing it');
  component = candidates[0][1];
}
const existing = imports.find(match => match[1] === component);
assert.ok(existing, `No unambiguous default import for ${component}`);
assert.ok(/Coverage|Chart|Visual/.test(component), `Unexpected section component ${component}`);
const invocation = source.match(new RegExp(`<${component}\\b[\\s\\S]*?\\/>`));
assert.ok(invocation && /\bproducts\s*=\s*\{/.test(invocation[0]), 'Existing chart does not receive products; refuse to guess an adapter');
source = source.replace(existing[0], `import ${component} from "@/components/category/EvidenceComparisonPanel";`);
await writeFile(path, source);
const modelPath = 'src/lib/evidence-chart.ts';
let model = await readFile(modelPath, 'utf8');
const original = 'if (amount.basis === "unspecified")';
assert.equal(model.split(original).length, 2);
model = model.replace(original, 'if (amount.basis === "unspecified" || amount.basis === "event")');
await writeFile(modelPath, model);
const uiPath = 'src/components/category/EvidenceComparisonPanel.tsx';
let ui = await readFile(uiPath, 'utf8');
ui = ui.replace('計算單位未明示，不繪製比較柱', '計算口徑未能可靠對齊，不繪製比較柱');
await writeFile(uiPath, ui);
const versionPath = 'src/lib/version.ts';
let version = await readFile(versionPath, 'utf8');
assert.match(version, /APP_VERSION = "1\.6\.1"/);
version = version.replace(/BUILD_NUMBER = "[^"]+"/, 'BUILD_NUMBER = "20260906.21"').replace(/BUILD_DATE = "[^"]+"/, 'BUILD_DATE = "2026-09-06"');
await writeFile(versionPath, version);
await mkdir('docs/review', {recursive:true});
await writeFile('docs/review/08-evidence-chart.md', `# 可解釋的保障數值視覺化\n\n原類別視覺元件：${component}（${existing[3]}）。只更改其在 CategoryDetail 的匯入，不改篩選結果、產品數字或其他頁面的狀態管理。\n\n## 已實作\n同名摘要項目選擇器、按明示港元年／日／旅程／終身單位分組的數值圖，及全部產品的可閱讀原文表格。柱形不按最大值排名、不標示最佳計劃；來源連到已存在的逐條 PDF evidence fingerprint。\n\n無上限保留文字，缺失不當零值，重複同名摘要不代選有利級別。區間、多幣種、未明單位及一般每次事故／住院／索償口徑未能對齊時不畫比較柱。即使金額可繪，仍未宣稱病房、地區、級別、自負額及保單例外已等同。\n\n## 測試\n6 組新增測試涵蓋無上限／缺失／未知、年與日分組、重複級別、每次口徑、有限柱寬，以及實際 route 匯入。整合 workflow 先驗證未整合時測試失敗，再接線並重跑測試、lint、build 與 filter regression。瀏覽器與 exact commit 結果以 PR checks 及 artifacts 為準。\n\n## 回退\nRevert 本 PR 即可；無資料庫遷移、未合併或部署 master。沒有以圖表取代逐條最新保單審核。\n`);
console.log(`Integrated ${component} from ${existing[3]}; unscoped per-event values remain textual.`);
